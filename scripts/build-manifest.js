/**
 * Regenerates public/assets/manifest.json by scanning the asset folders.
 *
 * Nobody should ever hand-edit JSON to add a photograph. Drop files into
 *   public/assets/<brand>/<category>/
 * and run `node scripts/build-manifest.js` (the portable build runs it too).
 *
 * The asset id is derived from its path, which is what makes the update rule
 * work: replace a file at the same path and every presentation using it
 * updates, because the id never changed.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ASSETS = path.join(ROOT, 'public/assets');

const BRANDS = { vigo: 'vigo', alessi: 'alessi', corporate: 'corporate' };

const CATEGORY_BY_FOLDER = {
  product: 'Product Photography',
  'product-photography': 'Product Photography',
  products: 'Product Photography',
  lifestyle: 'Lifestyle',
  recipes: 'Recipes',
  recipe: 'Recipes',
  retail: 'Retail',
  social: 'Social',
  packaging: 'Packaging',
  backgrounds: 'Backgrounds',
  background: 'Backgrounds',
  logos: 'Logos',
  icons: 'Icons',
};

const IMAGE = /\.(jpe?g|png|webp|avif|gif|svg)$/i;
const VIDEO = /\.(mp4|webm|mov)$/i;

const titleCase = (s) =>
  s
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());

function scan() {
  const assets = [];
  if (!fs.existsSync(ASSETS)) return assets;

  for (const brandDir of fs.readdirSync(ASSETS)) {
    const brand = BRANDS[brandDir.toLowerCase()];
    const brandPath = path.join(ASSETS, brandDir);
    if (!brand || !fs.statSync(brandPath).isDirectory()) continue;

    for (const catDir of fs.readdirSync(brandPath)) {
      const catPath = path.join(brandPath, catDir);
      if (!fs.statSync(catPath).isDirectory()) continue;
      const category = CATEGORY_BY_FOLDER[catDir.toLowerCase()] || titleCase(catDir);

      for (const file of fs.readdirSync(catPath)) {
        const full = path.join(catPath, file);
        if (!fs.statSync(full).isFile()) continue;
        const isImage = IMAGE.test(file);
        const isVideo = VIDEO.test(file);
        if (!isImage && !isVideo) continue;

        const base = file.replace(/\.[^.]+$/, '');
        assets.push({
          id: `${brand}-${catDir.toLowerCase()}-${base.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
          brand,
          category,
          name: titleCase(base),
          path: `/assets/${brandDir}/${catDir}/${file}`,
          kind: isVideo ? 'video' : 'image',
        });
      }
    }
  }
  assets.sort((a, b) => (a.brand + a.category + a.name).localeCompare(b.brand + b.category + b.name));
  return assets;
}

const assets = scan();
const out = {
  $comment:
    'GENERATED by scripts/build-manifest.js — do not hand-edit. Add files under public/assets/<brand>/<category>/ and re-run it.',
  generated: assets.length,
  assets,
};
fs.writeFileSync(path.join(ASSETS, 'manifest.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`manifest: ${assets.length} asset${assets.length === 1 ? '' : 's'}`);
if (assets.length) {
  const byBrand = {};
  assets.forEach((a) => (byBrand[a.brand] = (byBrand[a.brand] || 0) + 1));
  Object.entries(byBrand).forEach(([b, n]) => console.log(`  ${b}: ${n}`));
}
